-- CourtIQ PostgreSQL schema.
-- Import existing MySQL data separately after creating these tables.

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('student', 'warden', 'administrator')),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'suspended')),
    approval_status VARCHAR(20) NOT NULL DEFAULT 'approved'
        CHECK (approval_status IN ('pending', 'approved', 'rejected')),
    approval_decided_by INTEGER,
    approval_decided_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (approval_decided_by) REFERENCES users(id) ON DELETE SET NULL
        DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);
CREATE INDEX IF NOT EXISTS idx_users_status ON users (status);
CREATE INDEX IF NOT EXISTS idx_users_approval_status ON users (approval_status, role);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_lower ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users (LOWER(email));

CREATE TABLE IF NOT EXISTS hostel_profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    location VARCHAR(180),
    capacity INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rooms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id INTEGER NOT NULL,
    room_number VARCHAR(50) NOT NULL,
    room_type VARCHAR(60) DEFAULT 'Standard',
    capacity INTEGER NOT NULL DEFAULT 1,
    occupied INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'occupied', 'maintenance')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (hostel_id) REFERENCES hostel_profiles(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS accommodation_applications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    hostel_preference VARCHAR(150) NOT NULL,
    room_type VARCHAR(60) NOT NULL,
    application_status VARCHAR(20) NOT NULL DEFAULT 'submitted'
        CHECK (application_status IN ('submitted', 'pending', 'approved', 'rejected')),
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS maintenance_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no VARCHAR(100) NOT NULL UNIQUE,
    user_id INTEGER NOT NULL,
    hostel_id INTEGER,
    room_id INTEGER,
    hostel_name_snapshot VARCHAR(150),
    room_number_snapshot VARCHAR(50),
    title VARCHAR(180) NOT NULL,
    category VARCHAR(30) NOT NULL DEFAULT 'Other'
        CHECK (category IN ('Plumbing', 'Electrical', 'Furniture', 'Cleaning', 'Room Facilities', 'Security', 'Other')),
    description TEXT NOT NULL,
    priority VARCHAR(10) NOT NULL DEFAULT 'medium'
        CHECK (priority IN ('low', 'medium', 'high')),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'resolved', 'rejected')),
    latest_response TEXT,
    resolution_notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (hostel_id) REFERENCES hostel_profiles(id) ON DELETE SET NULL
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE SET NULL
        DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX IF NOT EXISTS idx_maintenance_hostel ON maintenance_requests (hostel_id, status);
CREATE INDEX IF NOT EXISTS idx_maintenance_filters ON maintenance_requests (status, category, hostel_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_maintenance_reference_lower ON maintenance_requests (LOWER(reference_no));

CREATE TABLE IF NOT EXISTS maintenance_request_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL,
    actor_id INTEGER,
    action VARCHAR(40) NOT NULL,
    previous_status VARCHAR(20)
        CHECK (previous_status IS NULL OR previous_status IN ('pending', 'in_progress', 'resolved', 'rejected')),
    new_status VARCHAR(20)
        CHECK (new_status IS NULL OR new_status IN ('pending', 'in_progress', 'resolved', 'rejected')),
    response TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (request_id) REFERENCES maintenance_requests(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL
        DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX IF NOT EXISTS idx_maintenance_history_request
    ON maintenance_request_history (request_id, created_at);
CREATE INDEX IF NOT EXISTS idx_maintenance_history_actor
    ON maintenance_request_history (actor_id);

CREATE TABLE IF NOT EXISTS payment_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    reference_no VARCHAR(60) NOT NULL UNIQUE,
    amount DECIMAL(10, 2) NOT NULL,
    balance DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'recorded'
        CHECK (status IN ('recorded', 'verified', 'pending_audit')),
    payment_date DATE NOT NULL,
    notes VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS student_profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE,
    full_name VARCHAR(150),
    student_number VARCHAR(50) UNIQUE,
    phone VARCHAR(30),
    course VARCHAR(150),
    year_of_study SMALLINT CHECK (year_of_study IS NULL OR year_of_study BETWEEN 0 AND 255),
    emergency_contact VARCHAR(180),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_student_number_lower
    ON student_profiles (LOWER(student_number)) WHERE student_number IS NOT NULL;

CREATE TABLE IF NOT EXISTS warden_assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warden_id INTEGER NOT NULL,
    hostel_id INTEGER NOT NULL,
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    UNIQUE (warden_id, hostel_id, active),
    FOREIGN KEY (warden_id) REFERENCES users(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (hostel_id) REFERENCES hostel_profiles(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS room_allocations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id INTEGER NOT NULL,
    student_id INTEGER NOT NULL,
    allocated_by INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'ended')),
    allocated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP,
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (allocated_by) REFERENCES users(id) ON DELETE RESTRICT
        DEFERRABLE INITIALLY DEFERRED
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_active_student
    ON room_allocations (student_id) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_allocations_room_status ON room_allocations (room_id, status);

CREATE TABLE IF NOT EXISTS notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    title VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,
    is_read SMALLINT NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX IF NOT EXISTS idx_notifications_user_read ON notifications (user_id, is_read);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id INTEGER,
    details JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
        DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_log (entity_type, entity_id);

CREATE OR REPLACE FUNCTION courtiq_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION courtiq_set_updated_at();
DROP TRIGGER IF EXISTS applications_set_updated_at ON accommodation_applications;
CREATE TRIGGER applications_set_updated_at BEFORE UPDATE ON accommodation_applications
    FOR EACH ROW EXECUTE FUNCTION courtiq_set_updated_at();
DROP TRIGGER IF EXISTS maintenance_set_updated_at ON maintenance_requests;
CREATE TRIGGER maintenance_set_updated_at BEFORE UPDATE ON maintenance_requests
    FOR EACH ROW EXECUTE FUNCTION courtiq_set_updated_at();
DROP TRIGGER IF EXISTS student_profiles_set_updated_at ON student_profiles;
CREATE TRIGGER student_profiles_set_updated_at BEFORE UPDATE ON student_profiles
    FOR EACH ROW EXECUTE FUNCTION courtiq_set_updated_at();
